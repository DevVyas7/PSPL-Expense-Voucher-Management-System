const axios = require('axios');

const BASE_URL = 'http://localhost:5000/api';

const runTests = async () => {
  console.log('=== STARTING AUTOMATED BACKEND INTEGRATION TESTS ===\n');
  let passed = 0;
  let failed = 0;

  const test = async (name, fn) => {
    try {
      await fn();
      console.log(`✓ [PASS] ${name}`);
      passed++;
    } catch (err) {
      console.error(`✗ [FAIL] ${name}`);
      console.error(`  Error: ${err.response?.data?.message || err.message}`);
      failed++;
    }
  };

  let employeeToken = '';
  let directorToken = '';
  let accountsToken = '';
  let createdVoucherId = '';

  // Test 1: Health check
  await test('Server health endpoint returns 200 OK', async () => {
    const res = await axios.get('http://localhost:5000/api/health');
    if (res.data.status !== 'online') throw new Error('Health status is not online');
  });

  // Test 2: Valid Employee login
  await test('Valid Employee login succeeds and returns JWT token & profile', async () => {
    const res = await axios.post(`${BASE_URL}/auth/login`, {
      email: 'employee@prachay.com',
      password: 'Password@123'
    });
    if (!res.data.token || res.data.user.role !== 'Employee') {
      throw new Error('Token missing or incorrect role');
    }
    if (res.data.user.password) {
      throw new Error('Password hash leaked in API response');
    }
    employeeToken = res.data.token;
  });

  // Test 3: Valid Director login
  await test('Valid Director login succeeds and returns JWT token', async () => {
    const res = await axios.post(`${BASE_URL}/auth/login`, {
      email: 'director@prachay.com',
      password: 'Password@123'
    });
    if (!res.data.token || res.data.user.role !== 'Director') {
      throw new Error('Token missing or incorrect role');
    }
    directorToken = res.data.token;
  });

  // Test 4: Valid Accounts Team login
  await test('Valid Accounts Team login succeeds', async () => {
    const res = await axios.post(`${BASE_URL}/auth/login`, {
      email: 'accounts@prachay.com',
      password: 'Password@123'
    });
    if (!res.data.token || res.data.user.role !== 'Accounts Team') {
      throw new Error('Token missing or incorrect role');
    }
    accountsToken = res.data.token;
  });

  // Test 5: Invalid credentials rejected
  await test('Invalid password fails with 401 Unauthorized', async () => {
    try {
      await axios.post(`${BASE_URL}/auth/login`, {
        email: 'employee@prachay.com',
        password: 'IncorrectPassword'
      });
      throw new Error('Login should have failed');
    } catch (err) {
      if (err.response?.status !== 401) throw err;
    }
  });

  // Test 6: Unauthenticated request to /vouchers rejected
  await test('Unauthenticated access to /api/vouchers returns 401', async () => {
    try {
      await axios.get(`${BASE_URL}/vouchers`);
      throw new Error('Unauthenticated request should have failed');
    } catch (err) {
      if (err.response?.status !== 401) throw err;
    }
  });

  // Test 7: Accounts Team cannot create vouchers (Role Authorization)
  await test('Accounts Team cannot create vouchers (returns 403 Forbidden)', async () => {
    try {
      await axios.post(
        `${BASE_URL}/vouchers`,
        {
          departmentName: 'Accounts',
          expenseTitle: 'Unauthorized Attempt',
          expenseCategory: 'Other',
          amount: 500
        },
        { headers: { Authorization: `Bearer ${accountsToken}` } }
      );
      throw new Error('Accounts Team should not be able to create vouchers');
    } catch (err) {
      if (err.response?.status !== 403) throw err;
    }
  });

  // Test 8: Employee creates a draft voucher
  await test('Employee creates a draft voucher with auto-generated unique ID', async () => {
    const res = await axios.post(
      `${BASE_URL}/vouchers`,
      {
        departmentName: 'Investment Banking',
        expenseTitle: 'Automated Test Travel Voucher',
        expenseCategory: 'Travel',
        expenseDescription: 'Travel claim generated by automated test runner.',
        amount: 8500
      },
      { headers: { Authorization: `Bearer ${employeeToken}` } }
    );
    if (!res.data.voucher || res.data.voucher.status !== 'Draft') {
      throw new Error('Voucher was not created with Draft status');
    }
    if (!res.data.voucher.voucherNumber.startsWith('EXP-')) {
      throw new Error('Voucher number format is invalid');
    }
    createdVoucherId = res.data.voucher._id;
  });

  // Test 9: Submitting voucher WITHOUT signature must fail
  await test('Submitting voucher without signature is rejected (returns 400)', async () => {
    try {
      await axios.post(
        `${BASE_URL}/vouchers/${createdVoucherId}/submit`,
        {},
        { headers: { Authorization: `Bearer ${employeeToken}` } }
      );
      throw new Error('Submission without signature should have been rejected');
    } catch (err) {
      if (err.response?.status !== 400) throw err;
    }
  });

  // Test 10: Submitting voucher WITH signature succeeds
  await test('Submitting voucher with signature transitions status to Pending Approval', async () => {
    const res = await axios.post(
      `${BASE_URL}/vouchers/${createdVoucherId}/submit`,
      { employeeSignature: '/uploads/sample-employee-sig.png' },
      { headers: { Authorization: `Bearer ${employeeToken}` } }
    );
    if (res.data.voucher.status !== 'Pending Approval') {
      throw new Error(`Expected Pending Approval but got ${res.data.voucher.status}`);
    }
  });

  // Test 11: Submitted voucher CANNOT be edited by employee
  await test('Submitted voucher is read-only and cannot be edited by employee (returns 400)', async () => {
    try {
      await axios.put(
        `${BASE_URL}/vouchers/${createdVoucherId}`,
        { expenseTitle: 'Attempting to edit submitted voucher' },
        { headers: { Authorization: `Bearer ${employeeToken}` } }
      );
      throw new Error('Editing non-draft voucher should have been rejected');
    } catch (err) {
      if (err.response?.status !== 400) throw err;
    }
  });

  // Test 12: Submitted voucher CANNOT be deleted by employee
  await test('Submitted voucher cannot be deleted by employee (returns 400)', async () => {
    try {
      await axios.delete(`${BASE_URL}/vouchers/${createdVoucherId}`, {
        headers: { Authorization: `Bearer ${employeeToken}` }
      });
      throw new Error('Deleting non-draft voucher should have been rejected');
    } catch (err) {
      if (err.response?.status !== 400) throw err;
    }
  });

  // Test 13: Employee CANNOT approve vouchers
  await test('Employee cannot approve vouchers (returns 403 Forbidden)', async () => {
    try {
      await axios.post(
        `${BASE_URL}/vouchers/${createdVoucherId}/approve`,
        { directorSignature: '/uploads/sample-director-sig.png' },
        { headers: { Authorization: `Bearer ${employeeToken}` } }
      );
      throw new Error('Employee should not have permission to approve');
    } catch (err) {
      if (err.response?.status !== 403) throw err;
    }
  });

  // Test 14: Director approval WITHOUT signature is rejected
  await test('Director approval without signature is rejected (returns 400)', async () => {
    try {
      await axios.post(
        `${BASE_URL}/vouchers/${createdVoucherId}/approve`,
        {},
        { headers: { Authorization: `Bearer ${directorToken}` } }
      );
      throw new Error('Approval without director signature should have been rejected');
    } catch (err) {
      if (err.response?.status !== 400) throw err;
    }
  });

  // Test 15: Director approval WITH signature succeeds
  await test('Director approval with signature transitions voucher to Approved', async () => {
    const res = await axios.post(
      `${BASE_URL}/vouchers/${createdVoucherId}/approve`,
      { directorSignature: '/uploads/sample-director-sig.png' },
      { headers: { Authorization: `Bearer ${directorToken}` } }
    );
    if (res.data.voucher.status !== 'Approved') {
      throw new Error(`Expected Approved but got ${res.data.voucher.status}`);
    }
    if (!res.data.voucher.approvalDate || !res.data.voucher.directorSignature) {
      throw new Error('Approval date or director signature not saved');
    }
  });

  // Test 16: An approved voucher CANNOT be re-approved or rejected
  await test('An approved voucher cannot be approved or rejected again (returns 400)', async () => {
    try {
      await axios.post(
        `${BASE_URL}/vouchers/${createdVoucherId}/reject`,
        { rejectionReason: 'Trying to reject already approved voucher' },
        { headers: { Authorization: `Bearer ${directorToken}` } }
      );
      throw new Error('Re-processing an approved voucher should have been rejected');
    } catch (err) {
      if (err.response?.status !== 400) throw err;
    }
  });

  // Test 17: Accounts Team can view approved voucher details
  await test('Accounts Team can view approved voucher and its signatures in read-only mode', async () => {
    const res = await axios.get(`${BASE_URL}/vouchers/${createdVoucherId}`, {
      headers: { Authorization: `Bearer ${accountsToken}` }
    });
    if (!res.data.voucher || res.data.voucher.status !== 'Approved') {
      throw new Error('Accounts Team failed to view approved voucher');
    }
    if (!res.data.voucher.employeeSignature || !res.data.voucher.directorSignature) {
      throw new Error('Signatures missing from voucher detail view');
    }
  });

  // Test 18: Director dashboard metrics
  await test('Director dashboard metrics return live MongoDB aggregation counts', async () => {
    const res = await axios.get(`${BASE_URL}/dashboard/director`, {
      headers: { Authorization: `Bearer ${directorToken}` }
    });
    if (res.data.data.approvedToday === undefined || res.data.data.pendingCount === undefined) {
      throw new Error('Dashboard metric fields are missing');
    }
  });

  // Test 19: Accounts dashboard metrics
  await test('Accounts dashboard metrics return total approved expense sum', async () => {
    const res = await axios.get(`${BASE_URL}/dashboard/accounts`, {
      headers: { Authorization: `Bearer ${accountsToken}` }
    });
    if (typeof res.data.data.totalApprovedAmount !== 'number') {
      throw new Error('Accounts totalApprovedAmount is not a number');
    }
  });

  console.log(`\n========================================`);
  console.log(`TEST SUMMARY: ${passed} PASSED, ${failed} FAILED`);
  console.log(`========================================\n`);

  if (failed > 0) process.exit(1);
  process.exit(0);
};

runTests();
